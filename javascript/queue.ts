//This is a Queue representation in Typescrpt.Queue uses the FIFO method to organize the elements. We will be implemnting queues with arrays


class Queues {
    //Initializin a queue array with values
    queue: string[] = []

    //This function helps check if the queue is empty
    isEmpty() {
        return this.queue.length === 0 ? true : false;
    }

    //This function helps  you add the data or value next to the current one 
    enqueue(value: string) {
        // adds the value next to the current one 
        this.queue[this.queue.length] = value;        
    }

    //This function helps you remove the first element in the array 
    dequeue() {
        if(this.isEmpty()) {
            return "Queue is empty"
        }

        const firstElement = this.queue[0]

        this.queue.shift()

        return firstElement 
    }
    
}

